import pandas as pd

# Student Marksheet analysis

data = {
    'roll_no': ['20', '19', '18', '17', '16', '15', '14', '13', '12', '11', '21', '22', '23', '24', '25'],
    's_name': ['Bablu Nishad','Rohit Sharma','Amit Verma','Sachin Yadav','Rajesh Singh','Naman Gupta','Aditya Bharti',
        'Manish Thakre','Abhishek Yadav','Vikas Yadav','Rohan Donge','Manoj Sharma','Vivek Mishra','Suresh Singh','Nikhil Kumar'],
    'branch': ['CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE', 'CSE'],
    'python': [85, 92, 78, 88, 45, 95, 62, 74, 91, 35, 83, 55, 89, 68, 96],
    'java': [78, 95, 65, 82, 50, 91, 58, 70, 89, 40, 86, 60, 84, 72, 94],
    'dbms': [90, 89, 72, 85, 42, 96, 65, 68, 94, 38, 80, 58, 91, 70, 98],
    'dsa': [88, 94, 70, 80, 48, 93, 60, 72, 90, 32, 85, 62, 87, 66, 95],
    'att_percent': [92, 96, 85, 90, 76, 98, 82, 88, 94, 65, 91, 80, 93, 84, 99]
}

df = pd.DataFrame(data)

# save to csv so it can be reloaded
df.to_csv('student_data.csv', index=False)

# reload from csv
df = pd.read_csv('student_data.csv')

# total & avg calculating
df['total_marks'] = df['python'] + df['java'] + df['dbms'] + df['dsa']
df['avg_marks'] = df['total_marks'] / 4.0

# grade & pass fail check
grade_list = []
status_list = []

for idx, k in df.iterrows():
    p = k['python']
    j = k['java']
    db = k['dbms']
    ds = k['dsa']
    av = k['avg_marks']

    # less than 40 fail
    if p < 40 or j < 40 or db < 40 or ds < 40:
        status_list.append('FAIL')
    else:
        status_list.append('PASS')

    if av >= 90:
        grade_list.append('A+')
    elif av >= 80:
        grade_list.append('A')
    elif av >= 70:
        grade_list.append('B')
    elif av >= 60:
        grade_list.append('C')
    elif av >= 50:
        grade_list.append('D')
    else:
        grade_list.append('F')

df['grade'] = grade_list
df['status'] = status_list

print("All Students Record:")
print(df[['roll_no', 's_name', 'branch', 'total_marks', 'avg_marks', 'grade', 'status']])

# overall stats
tot_pass = 0
for st in df['status']:
    if st == 'PASS':
        tot_pass = tot_pass + 1

tot_fail = len(df) - tot_pass

print("\n    Final Summary    ")
print("Total Students:", len(df))
print("Passed:", tot_pass)
print("Failed:", tot_fail)
print("Class Average Marks:", round(df['avg_marks'].mean(), 2))

# highest and lowest
high_idx = df['avg_marks'].idxmax()
low_idx = df['avg_marks'].idxmin()

print("\nHighest Scorer:", df.loc[high_idx, 's_name'], "with", df.loc[high_idx, 'avg_marks'])
print("Lowest Scorer:", df.loc[low_idx, 's_name'], "with", df.loc[low_idx, 'avg_marks'])

# subject means
subjects = ['python', 'java', 'dbms', 'dsa']
print("\nSubject Averages:")
for sub in subjects:
    print(sub.upper(), "-> Mean:", round(df[sub].mean(), 2), "| Max:", df[sub].max(), "| Min:", df[sub].min())